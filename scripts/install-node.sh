#!/usr/bin/env bash
set -euo pipefail

JOE_VERSION="0.32.0"
SERVER=""
ENROLL=""
NODE_NAME="$(hostname 2>/dev/null || echo managed-node)"
NODE_NAME_EXPLICIT=0
INSTALL_DIR="/opt/joe-node"
VERBOSE=0

usage() {
  cat <<'EOF'
Usage: install-node.sh --server https://controller.example.com [--enroll TOKEN] [--name NAME] [--install-dir PATH] [--verbose]

Installs the managed Joe Cloud agent and guarded host bridge. The customer node does
not install the Joe controller, web GUI, MCP endpoint, Git repository, or Docker stack.
For first-time enrollment use the one-time command generated by Devices -> Add device.
EOF
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --server) SERVER="${2:-}"; shift 2 ;;
    --enroll|--pairing-code) ENROLL="${2:-}"; shift 2 ;;
    --name) NODE_NAME="${2:-}"; NODE_NAME_EXPLICIT=1; shift 2 ;;
    --install-dir) INSTALL_DIR="${2:-}"; shift 2 ;;
    --verbose) VERBOSE=1; shift ;;
    -h|--help) usage; exit 0 ;;
    *) echo "Unknown argument: $1" >&2; usage >&2; exit 2 ;;
  esac
done

[[ ${EUID:-$(id -u)} -eq 0 ]] || { echo "Run this installer with sudo/root." >&2; exit 1; }
[[ "$SERVER" == https://* && "$SERVER" != *[[:space:]]* ]] || { echo "--server must be an HTTPS URL without whitespace." >&2; exit 1; }
[[ "$NODE_NAME" =~ ^[A-Za-z0-9._-]{1,64}$ ]] || { echo "--name may contain only letters, numbers, dot, underscore and hyphen (max 64)." >&2; exit 1; }
[[ "$INSTALL_DIR" =~ ^/[A-Za-z0-9._/-]+$ && "$INSTALL_DIR" != "/" ]] || { echo "--install-dir must be a simple absolute non-root path." >&2; exit 1; }
[[ "$INSTALL_DIR" != *"/../"* && "$INSTALL_DIR" != */.. && "$INSTALL_DIR" != *"/./"* && "$INSTALL_DIR" != */. ]] || { echo "--install-dir cannot contain dot path components." >&2; exit 1; }
if [[ -n "$ENROLL" && ! "$ENROLL" =~ ^[A-Za-z0-9_-]{12,160}$ ]]; then
  echo "--enroll contains an invalid one-time token." >&2
  exit 1
fi
SERVER="${SERVER%/}"

command -v systemctl >/dev/null 2>&1 || { echo "Joe managed nodes require Linux with systemd." >&2; exit 1; }
command -v curl >/dev/null 2>&1 || { echo "curl is required to install Joe." >&2; exit 1; }

missing=()
for cmd in python3 tar tmux; do
  command -v "$cmd" >/dev/null 2>&1 || missing+=("$cmd")
done
if ((${#missing[@]})); then
  echo "Installing required Joe runtime packages: ${missing[*]}"
  if command -v apt-get >/dev/null 2>&1; then
    export DEBIAN_FRONTEND=noninteractive
    apt-get update
    apt-get install -y --no-install-recommends python3 tar tmux ca-certificates
  elif command -v dnf >/dev/null 2>&1; then
    dnf install -y python3 tar tmux ca-certificates
  elif command -v yum >/dev/null 2>&1; then
    yum install -y python3 tar tmux ca-certificates
  else
    echo "Missing prerequisites: ${missing[*]}. Install them, then run the same Joe command again." >&2
    exit 1
  fi
fi

for cmd in python3 tar tmux; do
  command -v "$cmd" >/dev/null 2>&1 || { echo "Required command is still unavailable after package installation: $cmd" >&2; exit 1; }
done

python3 - "$SERVER" <<'PYURL'
import sys
from urllib.parse import urlsplit
u = urlsplit(sys.argv[1])
if u.scheme != "https" or not u.hostname or u.username or u.password or u.query or u.fragment or u.path not in ("", "/"):
    raise SystemExit("--server must be a clean HTTPS origin, for example https://controller.example.com")
PYURL

if [[ $NODE_NAME_EXPLICIT -eq 0 && -s /var/lib/joe-mcp-agent/config.json ]]; then
  existing_name="$(python3 - <<'PY' 2>/dev/null || true
import json
from pathlib import Path
p=Path('/var/lib/joe-mcp-agent/config.json')
try:
    d=json.loads(p.read_text(encoding='utf-8'))
    print(str(d.get('name') or ''))
except Exception:
    pass
PY
)"
  if [[ "$existing_name" =~ ^[A-Za-z0-9._-]{1,64}$ ]]; then
    NODE_NAME="$existing_name"
  fi
fi

if [[ -e "$INSTALL_DIR" && ! -f "$INSTALL_DIR/.joe-node-install" ]]; then
  echo "Refusing to replace existing non-Joe directory: $INSTALL_DIR" >&2
  exit 1
fi

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
BUNDLE="$TMP/joe-node.tar.gz"
CHECKSUM="$TMP/joe-node.sha256"
EXTRACT="$TMP/extract"
mkdir -p "$EXTRACT"

echo "Installing Joe Agent..."
echo "[1/4] Downloading and verifying the secure package..."
curl --fail --silent --show-error --location --proto '=https' --tlsv1.2 "$SERVER/node-bundle.tar.gz" -o "$BUNDLE"
curl --fail --silent --show-error --location --proto '=https' --tlsv1.2 "$SERVER/node-bundle.sha256" -o "$CHECKSUM"

python3 - "$BUNDLE" "$CHECKSUM" "$EXTRACT" <<'PY'
import hashlib, re, sys, tarfile
from pathlib import Path
bundle = Path(sys.argv[1])
checksum = Path(sys.argv[2]).read_text(encoding='utf-8').strip().split()[0]
dest = Path(sys.argv[3]).resolve()
if not re.fullmatch(r'[0-9a-f]{64}', checksum):
    raise SystemExit('Joe node checksum response is invalid')
actual = hashlib.sha256(bundle.read_bytes()).hexdigest()
if actual != checksum:
    raise SystemExit('Joe node package checksum verification failed')
with tarfile.open(bundle, 'r:gz') as archive:
    members = archive.getmembers()
    if not members:
        raise SystemExit('Joe node bundle is empty')
    for member in members:
        name = member.name
        if name.startswith('/') or '..' in Path(name).parts:
            raise SystemExit(f'Unsafe path in Joe node bundle: {name}')
        target = (dest / name).resolve()
        if target != dest and dest not in target.parents:
            raise SystemExit(f'Joe node bundle path escapes destination: {name}')
        if member.issym() or member.islnk():
            raise SystemExit(f'Joe node bundle contains unsupported link: {name}')
        if not (member.isfile() or member.isdir()):
            raise SystemExit(f'Joe node bundle contains unsupported archive member: {name}')
    archive.extractall(dest)
PY

for required in scripts/install-host-bridge.sh scripts/managed_node_update.py deploy/joe-cli.in deploy/joe-mcp-node-agent.service.in deploy/joe-mcp-node-update.service.in src/joe_cli.py src/node_agent.py src/node_executor.py src/device_agent_client.py; do
  [[ -f "$EXTRACT/$required" ]] || { echo "Joe Agent package is incomplete: $required" >&2; exit 1; }
done
chmod 0755 "$EXTRACT/scripts/install-host-bridge.sh"

# Stop the pre-v0.20 Docker-based managed-node runtime before replacing its files.
if [[ -f "$INSTALL_DIR/docker-compose.node.yml" ]] && command -v docker >/dev/null 2>&1 && docker compose version >/dev/null 2>&1; then
  echo "Migrating legacy Docker-based Joe Node to the managed systemd agent ..."
  (cd "$INSTALL_DIR" && docker compose -f docker-compose.node.yml down --remove-orphans) || true
fi

mkdir -p "$INSTALL_DIR"
for item in config deploy scripts src; do
  rm -rf "$INSTALL_DIR/$item"
  cp -a "$EXTRACT/$item" "$INSTALL_DIR/$item"
done
chmod 0755 "$INSTALL_DIR/scripts/install-host-bridge.sh" "$INSTALL_DIR/scripts/managed_node_update.py"
cp "$INSTALL_DIR/config/workspaces.managed.json" "$INSTALL_DIR/config/workspaces.json"
chmod 0644 "$INSTALL_DIR/config/workspaces.json"
printf '%s\n' "$JOE_VERSION" > "$INSTALL_DIR/.joe-node-install"
chmod 0600 "$INSTALL_DIR/.joe-node-install"

# If this server is upgrading from the old full-node layout, keep custom workspaces
# but revoke modify/deploy permission from Joe's own runtime directory.
python3 - "$INSTALL_DIR" <<'PYWORK'
import json
import sys
from pathlib import Path
root = str(Path(sys.argv[1]).resolve())
path = Path('/var/lib/joe-mcp-work/workspaces.json')
if path.is_file():
    try:
        data = json.loads(path.read_text(encoding='utf-8'))
    except Exception:
        data = None
    changed = False
    if isinstance(data, dict) and isinstance(data.get('workspaces'), dict):
        for profile in data['workspaces'].values():
            if not isinstance(profile, dict):
                continue
            if str(Path(str(profile.get('root') or '/')).resolve(strict=False)) != root:
                continue
            permissions = profile.setdefault('permissions', {})
            if isinstance(permissions, dict):
                permissions['modify'] = False
                permissions['deploy'] = False
                changed = True
    if changed:
        tmp = path.with_suffix('.tmp')
        tmp.write_text(json.dumps(data, indent=2, sort_keys=True) + '\n', encoding='utf-8')
        tmp.chmod(0o600)
        tmp.replace(path)
PYWORK

cd "$INSTALL_DIR"
echo "[2/4] Installing protected host services..."
if [[ "$VERBOSE" -eq 1 ]]; then
  JOE_MANAGED_NODE=1 JOE_INSTALL_VERBOSE=1 ./scripts/install-host-bridge.sh
else
  if ! JOE_MANAGED_NODE=1 JOE_INSTALL_VERBOSE=0 ./scripts/install-host-bridge.sh >"$TMP/host-services.log" 2>&1; then
    echo "Host service installation failed. Diagnostic output:" >&2
    cat "$TMP/host-services.log" >&2
    exit 1
  fi
fi

if [[ ! -s /var/lib/joe-mcp-agent/config.json ]]; then
  echo "[3/4] Enrolling this device with your Joe account..."
  if [[ -n "$ENROLL" ]]; then
    if [[ "$VERBOSE" -eq 1 ]]; then
      python3 "$INSTALL_DIR/src/device_agent_client.py" --enroll-only --server "$SERVER" --name "$NODE_NAME" --pairing-code "$ENROLL"
    elif ! python3 "$INSTALL_DIR/src/device_agent_client.py" --enroll-only --server "$SERVER" --name "$NODE_NAME" --pairing-code "$ENROLL" >"$TMP/enroll.log" 2>&1; then
      echo "Device enrollment failed. Diagnostic output:" >&2
      cat "$TMP/enroll.log" >&2
      exit 1
    fi
  else
    echo "No one-time enrollment token was supplied. Enter the pairing code from Devices -> Add device."
    python3 "$INSTALL_DIR/src/device_agent_client.py" --enroll-only --server "$SERVER" --name "$NODE_NAME"
  fi
else
  echo "[3/4] Existing Joe device found. Preserving its identity..."
fi

install -d -m 0700 /var/lib/joe-mcp-agent
escaped_root="${INSTALL_DIR//\\/\\\\}"; escaped_root="${escaped_root//&/\\&}"; escaped_root="${escaped_root//|/\\|}"
escaped_name="${NODE_NAME//\\/\\\\}"; escaped_name="${escaped_name//&/\\&}"; escaped_name="${escaped_name//|/\\|}"
sed -e "s|@PROJECT_ROOT@|$escaped_root|g" -e "s|@NODE_NAME@|$escaped_name|g" -e "s|@JOE_VERSION@|$JOE_VERSION|g" \
  "$INSTALL_DIR/deploy/joe-mcp-node-agent.service.in" > /etc/systemd/system/joe-mcp-node-agent.service
sed -e "s|@PROJECT_ROOT@|$escaped_root|g" \
  "$INSTALL_DIR/deploy/joe-mcp-node-update.service.in" > /etc/systemd/system/joe-mcp-node-update.service
chmod 0644 /etc/systemd/system/joe-mcp-node-agent.service /etc/systemd/system/joe-mcp-node-update.service

# Retire the old lightweight presence agent if it exists. The managed agent replaces it.
if systemctl list-unit-files joe-mcp-device-agent.service >/dev/null 2>&1; then
  systemctl disable --now joe-mcp-device-agent.service >/dev/null 2>&1 || true
fi

systemctl daemon-reload
if [[ "$VERBOSE" -eq 1 ]]; then
  systemctl enable --now joe-mcp-node-agent.service
else
  systemctl enable --now joe-mcp-node-agent.service >/dev/null 2>&1
fi

echo "[4/4] Verifying services and controller connection..."
for _ in $(seq 1 20); do
  systemctl is-active --quiet joe-mcp-host-bridge.service \
    && systemctl is-active --quiet joe-mcp-session-host.service \
    && systemctl is-active --quiet joe-mcp-node-agent.service \
    && break
  sleep 1
done
systemctl is-active --quiet joe-mcp-host-bridge.service || { echo "Joe host bridge failed to start." >&2; exit 1; }
systemctl is-active --quiet joe-mcp-session-host.service || { echo "Joe persistent-session host failed to start." >&2; exit 1; }
systemctl is-active --quiet joe-mcp-node-agent.service || { echo "Joe managed agent failed to start." >&2; journalctl -u joe-mcp-node-agent.service -n 30 --no-pager >&2 || true; exit 1; }

CONTROLLER_REACHABLE=0
for _ in $(seq 1 5); do
  if curl --fail --silent --show-error --proto '=https' --tlsv1.2 "$SERVER/health" >/dev/null 2>&1; then
    CONTROLLER_REACHABLE=1
    break
  fi
  sleep 1
done
[[ "$CONTROLLER_REACHABLE" -eq 1 ]] || { echo "Joe services started, but the controller health check could not be reached." >&2; exit 1; }

DEVICE_ID="$(python3 - <<'PY' 2>/dev/null || true
import json
from pathlib import Path
try:
    print(json.loads(Path('/var/lib/joe-mcp-agent/config.json').read_text(encoding='utf-8')).get('device_id',''))
except Exception:
    pass
PY
)"

echo
echo "Joe Agent is ready."
echo "Device: $NODE_NAME"
echo "Controller: $SERVER"
echo "Agent: running"
echo "Connection: controller reachable"
echo "Status: ready in Joe Devices"
echo
echo "Joe connects outbound over HTTPS. No inbound management port was opened."
if [[ "$VERBOSE" -eq 1 ]]; then
  echo "Internal device ID: ${DEVICE_ID:-registered}"
  echo "This managed node contains only the Joe Agent runtime, not the Joe Cloud controller or customer web app."
fi
